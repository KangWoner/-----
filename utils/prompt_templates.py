def create_full_prompt(user_message, conversation_history=None):
    """
    사용자 메시지와 대화 기록을 바탕으로 완전한 프롬프트 생성

    Args:
        user_message (str): 사용자의 최근 메시지
        conversation_history (list): 이전 대화 기록 [{role, content}, ...]

    Returns:
        list: Claude API에 전달할 메시지 리스트
    """
    messages = []

    # 이전 대화 기록이 있으면 추가
    if conversation_history:
        for msg in conversation_history:
            messages.append({
                "role": msg.get("role", "user"),
                "content": msg.get("content", "")
            })

    # 현재 사용자 메시지 추가
    messages.append({
        "role": "user",
        "content": user_message
    })

    return messages
