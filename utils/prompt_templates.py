# 첫 만남 프롬프트
# ============================================

def get_welcome_prompt(problem_text=None):
    """
    학생이 처음 문제를 입력했을 때 사용하는 프롬프트

    Args:
        problem_text (str): 학생이 입력한 문제

    Returns:
        str: 환영 메시지와 함께 문제 분석 시작을 유도하는 프롬프트
    """
    if problem_text:
        return f"""학생이 다음 문제를 가지고 왔습니다:
"{problem_text}"

친절하게 환영하고, 이 문제를 어떻게 시작하면 좋을지
학생 스스로 생각해볼 수 있도록 질문해주세요.

답을 알려주지 말고, 문제를 이해했는지 먼저 확인하세요."""
    else:
        return "학생을 환영하고, 어떤 문제를 풀고 싶은지 물어보세요."


# ============================================
# 힌트 요청 프롬프트 (3단계)
# ============================================

def get_hint_prompt(level, problem_text, conversation_context):
    """
    학생이 힌트를 요청했을 때 단계별로 다른 힌트 제공

    Args:
        level (int): 힌트 레벨 (1, 2, 3)
        problem_text (str): 현재 풀고 있는 문제
        conversation_context (str): 지금까지의 대화 내용

    Returns:
        str: 힌트 제공 프롬프트
    """
    hints = {
        1: """학생이 첫 번째 힌트를 요청했습니다.

아주 작은 힌트만 주세요:
- 문제를 푸는 "방향"만 제시
- 여전히 질문 형태로
- 예: "이런 문제는 ___부터 시작하면 좋아요. 문제에서 ___를 찾아볼까요?"

답을 주지 마세요!""",

        2: """학생이 두 번째 힌트를 요청했습니다.

조금 더 구체적인 힌트를 주세요:
- 다음에 해야 할 "단계"를 알려주기
- 하지만 여전히 학생이 직접 계산하도록
- 예: "좋아요! 그럼 이제 양쪽에 ___를 해보면 어떨까요?"

아직 답은 주지 마세요!""",

        3: """학생이 세 번째 힌트를 요청했습니다.

거의 답에 가까운 힌트를 주세요:
- 구체적인 계산 방법 제시
- 하지만 최종 답은 학생이 직접 구하도록
- 예: "양쪽에 5를 빼면 2x = 8이 돼요. 이제 x를 구하려면 어떻게 해야 할까요?"

마지막 계산은 학생에게 맡기세요!"""
    }

    return f"""{hints.get(level, hints[1])}

현재 문제: {problem_text}

지금까지의 대화:
{conversation_context}"""


